/**
 * Макетный «движок»: подбирает один из готовых ответов по ключевым словам.
 * В реальной системе здесь будет запрос к бэкенду поиска.
 */
export function classifyQuery(raw: string): AnswerType {
  const q = raw.toLowerCase();
  if (/основан/.test(q)) return 'deleted';
  if (/ответствен|перрон/.test(q)) return 'table';
  if (/ранжир|методик|приказ\s*№?\s*\d+/.test(q)) return 'list';
  if (/монолит|срок/.test(q)) return 'diverge';
  if (/статус|готовност/.test(q)) return 'status';
  if (/задерж|металл|мер[ыа]? принят|поставк/.test(q)) return 'summary';
  return 'empty';
}

